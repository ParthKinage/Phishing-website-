"""Build the online (Vercel) deployment bundle in deploy/vercel/.

The bundle holds only what the hosted API needs: the API, the extractor,
the served XGBoost model in XGBoost's JSON format, and slim requirements
(no pandas / scikit-learn / shap, to stay within Vercel's function size
limit). It runs in public mode (PHISHING_PUBLIC=1): private addresses are
refused, the fake phishing demo pages are not included, and clients are
rate-limited.

Re-run after retraining or after changing api/ or src/extract.py:
    python -m src.build_deploy
"""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "deploy" / "vercel"

COPY = [
    "api/__init__.py",
    "api/main.py",
    "api/static/index.html",  # the try-it page; demo-*.html are left out on purpose
    "src/__init__.py",
    "src/extract.py",
    "src/features.py",
    "models/serving.json",
]

APP_PY = '''"""Vercel entry point. Generated by `python -m src.build_deploy`; do not edit."""
import os

os.environ.setdefault("PHISHING_PUBLIC", "1")  # public-mode safeguards

from api.main import app  # noqa: E402,F401
'''

# Same versions as requirements.txt; xgboost-cpu is the CPU-only build of
# xgboost (same `xgboost` module, without the large GPU libraries).
REQUIREMENTS = """\
fastapi==0.143.0
pydantic==2.14.0
xgboost-cpu==3.4.1
numpy==2.5.3
scipy==1.18.1
requests==2.34.2
beautifulsoup4==4.15.0
tldextract==5.4.0
"""

README = """# Online deployment bundle (generated)

Generated by `python -m src.build_deploy` from the project's own code; do
not edit these files directly. Deployed to Vercel with this folder as the
project's root directory. See the main README.
"""


def main():
    serving = json.loads((ROOT / "models" / "serving.json").read_text())
    native = serving.get("native_model_file")
    if not native:
        raise SystemExit("The served model has no native XGBoost export; the slim "
                         "deployment needs it (retrain with python -m src.train).")
    # Rebuild from scratch, but keep the Vercel CLI's link (.vercel/), its
    # local token file (.env.local) and the .gitignore it created.
    keep = {".vercel", ".env.local", ".gitignore"}
    if OUT.exists():
        for p in OUT.iterdir():
            if p.name in keep:
                continue
            shutil.rmtree(p) if p.is_dir() else p.unlink()
    for rel in COPY + [f"models/{native}"]:
        dest = OUT / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / rel, dest)
    (OUT / "app.py").write_text(APP_PY)
    (OUT / "requirements.txt").write_text(REQUIREMENTS)
    (OUT / ".python-version").write_text("3.13\n")
    (OUT / "README.md").write_text(README)
    # Never upload local secrets or the CLI link with a deployment.
    (OUT / ".vercelignore").write_text(".env*\n.vercel\nREADME.md\n")
    gitignore = OUT / ".gitignore"
    lines = gitignore.read_text().split() if gitignore.exists() else []
    gitignore.write_text("\n".join(dict.fromkeys(lines + [".vercel", ".env*"])) + "\n")
    files = sorted(p.relative_to(OUT).as_posix() for p in OUT.rglob("*") if p.is_file())
    print(f"Wrote {len(files)} files to {OUT}:")
    for f in files:
        print("  " + f)


if __name__ == "__main__":
    main()
